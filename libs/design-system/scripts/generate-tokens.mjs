/**
 * generate-tokens.mjs
 *
 * Generates src/lib/styles/tokens.css from src/lib/tokens/colors.json.
 * Single source of truth for design system color tokens.
 *
 * Usage: node scripts/generate-tokens.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");

// --- Read colors.json ---
const colors = JSON.parse(readFileSync(path.resolve(root, "src/lib/tokens/colors.json"), "utf-8"));

// --- Helpers ---

/**
 * Filter theme tokens only (excludes raw palettes like "zinc")
 * Theme tokens have matching keys in light and dark mode.
 */
const THEME_KEYS = new Set([
  "background",
  "foreground",
  "card",
  "card-foreground",
  "popover",
  "popover-foreground",
  "primary",
  "primary-foreground",
  "secondary",
  "secondary-foreground",
  "muted",
  "muted-foreground",
  "accent",
  "accent-foreground",
  "destructive",
  "destructive-foreground",
  "border",
  "input",
  "ring",
  "semantic-success",
  "semantic-warning",
  "semantic-info",
  "semantic-error",
]);

/**
 * Converts a token dictionary into CSS custom properties block.
 * Filters keys to only include theme tokens.
 */
const toVars = (obj, indent = "  ") =>
  Object.entries(obj)
    .filter(([key]) => THEME_KEYS.has(key))
    .map(([key, value]) => `${indent}--${key}: ${value};`)
    .join("\n");

// --- Generate CSS ---
const css = `/* ==========================================================
 * tokens.css — AUTO-GENERATED
 * Do not edit this file directly.
 * Source of truth: src/lib/tokens/colors.json
 * Regenerate: node scripts/generate-tokens.mjs
 * ========================================================== */

@import url("https://fonts.googleapis.com/css2?family=Inter:wght@300;400;500;600;700&family=JetBrains+Mono:wght@400;500;700&family=Space+Mono:wght@700&display=swap");

/* ----------------------------------------------------------
 * Base — light theme as default on :root
 * Required for Tailwind @theme inline resolution at build time.
 * ---------------------------------------------------------- */
:root {
  --radius: 0.5rem;

${toVars(colors.light)}
}

/* ----------------------------------------------------------
 * Explicit light theme
 * ---------------------------------------------------------- */
.light,
[data-theme="light"] {
${toVars(colors.light)}
}

/* ----------------------------------------------------------
 * Dark theme
 * ---------------------------------------------------------- */
.dark,
[data-theme="dark"] {
${toVars(colors.dark)}
}
`;

// --- Write file ---
const outputPath = path.resolve(root, "src/lib/styles/tokens.css");
writeFileSync(outputPath, css, "utf-8");

console.log("✅ tokens.css generated from colors.json");
console.log(`   → ${outputPath}`);
